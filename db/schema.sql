-- TeamTask database schema (Supabase Postgres).
-- Apply once to a new project. Safe to re-run: every statement is idempotent.
--
-- Row Level Security is enabled on every table with NO policies. That blocks
-- Supabase's public REST API (anon/authenticated keys) from reading or writing
-- the tables. The FastAPI app connects with the database role from DATABASE_URL,
-- which owns the tables and is not affected by RLS.

create table if not exists public.tasks (
    id           bigint generated by default as identity primary key,
    title        text not null check (char_length(title) between 1 and 200),
    description  text check (description is null or char_length(description) <= 1000),
    priority     text not null default 'medium' check (priority in ('low', 'medium', 'high')),
    status       text not null default 'pending' check (status in ('pending', 'completed')),
    due_date     date,
    created_at   timestamptz not null default now(),
    completed_at timestamptz
);

create table if not exists public.subtasks (
    id         bigint generated by default as identity primary key,
    task_id    bigint not null references public.tasks (id) on delete cascade,
    title      text not null check (char_length(title) between 1 and 200),
    status     text not null default 'pending' check (status in ('pending', 'completed')),
    created_at timestamptz not null default now()
);

create index if not exists subtasks_task_id_idx on public.subtasks (task_id);

create table if not exists public.ai_logs (
    id         bigint generated by default as identity primary key,
    endpoint   text not null,
    input_text text,
    model      text,
    created_at timestamptz not null default now()
);

alter table public.tasks    enable row level security;
alter table public.subtasks enable row level security;
alter table public.ai_logs  enable row level security;
